"""Latency / model-size / cost table for Review 2 from logs that already exist (retrieval latencies, Qwen meta and run files).

Usage: python -m scripts.review2_cost_table
Writes output/review2/cost_latency.md. Rows whose input file is missing are shown as 'pending'.
"""

import argparse
import json
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parent.parent
QWEN = ROOT / "output/review2/qwen"


RUNS = (("V2 qlora_r16_e1", "all CV + JD", QWEN / "run_config.json"),
        ("V3a qlora_r16_v3mix", "no external CVs, gold x4", QWEN / "v3a/run_config.json"),
        ("V3b qlora_r16_v3all", "all CVs, gold x4", QWEN / "v3b/run_config.json"))
GENERATIONS = ("base_test", "ft_test", "base_rp_test", "v2_rp_test", "v3_rp_test", "v3b_rp_test")


def pct(values: list[float], q: float) -> float:
    s = sorted(values)
    return s[min(len(s) - 1, int(q * len(s)))]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--gpu-price", type=float, default=1.79, help="$/hr of the A100 80GB (SXM and PCIe both $1.79 Secure, Runpod read)")
    args = p.parse_args()
    md = ["# Review 2 - latency, model size and cost (generated by scripts/review2_cost_table.py)\n"]

    lat = load(ROOT / "output/retrieval/benchmark_v2/latencies.json") or []
    # Settings from output/retrieval/benchmark_v2/report.md: BGE-M3 + BGE reranker (CUDA FP16, batch 1), precomputed query
    # vectors, model startup excluded. Dense and BM25 are shared across pools, so they are listed once.
    md += ["## Retrieval pipeline latency per CV query (ms; BGE-M3 + BGE reranker on local GPU, startup excluded)\n",
           "| Stage | Pool | n | median | p95 |", "|---|---|---|---|---|"]
    for stage, pools in (("dense_ms", ["primary"]), ("bm25_ms", ["primary"]), ("fusion_ms", ["primary"]),
                         ("rerank_ms", ["primary", "expanded"]), ("flow_ms", ["full_corpus"])):
        for pool in pools:
            vals = [r[stage] for r in lat if r["pool"] == pool and stage in r]
            if vals:
                name = {"flow_ms": "end-to-end flow"}.get(stage, stage[:-3])
                md.append(f"| {name} | {pool if stage in ('rerank_ms', 'flow_ms') else 'all'} | {len(vals)} | {median(vals):.1f} | {pct(vals, 0.95):.1f} |")

    md += ["\n## Qwen2.5-7B-Instruct extraction\n", "| Item | Value |", "|---|---|",
           "| Base model | Qwen2.5-7B-Instruct, 7.6B parameters (frozen) |", "| Training method | QLoRA 4-bit, LoRA r=16 alpha=32 |"]
    adapter = QWEN / "adapter/adapter_model.safetensors"
    md.append(f"| Adapter size | {adapter.stat().st_size / 2**20:.0f} MB (r=16, same for every run) |" if adapter.exists() else "| Adapter size | pending |")
    md += ["\n### Training runs (QLoRA 4-bit, all linear layers, 1 epoch, single seed)\n",
           "| Run | Data | Rows (dropped) | GPU | Peak memory | Time | GPU cost |", "|---|---|---|---|---|---|---|"]
    for name, data, path in RUNS:
        cfg = load(path)
        if not cfg:
            md.append(f"| {name} | {data} | pending | | | | |")
            continue
        hours = cfg["train_seconds"] / 3600
        md.append(f"| {name} | {data} | {cfg['train_rows']} ({len(cfg['train_dropped'])}) | {cfg['gpu']} | {cfg['peak_mem_gb']} GB | "
                  f"{hours * 60:.0f} min | ${hours * args.gpu_price:.2f} |")
    md += ["\n### Generation on the test split (90 docs, vLLM greedy, batched)\n",
           "| Predictions | Model | Repetition penalty | Time | Output tok/s |", "|---|---|---|---|---|"]
    for name in GENERATIONS:
        meta = load(QWEN / f"{name}.meta.json")
        md.append(f"| {name} | {meta['adapter'] or 'raw Qwen'} | {meta.get('repetition_penalty', 1.0)} | {meta['seconds']:.0f} s | "
                  f"{meta['tokens_per_second']:.0f} |" if meta else f"| {name} | pending | | | |")
    (ROOT / "output/review2/cost_latency.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
