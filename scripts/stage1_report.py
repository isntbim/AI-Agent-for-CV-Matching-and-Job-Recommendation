"""Stage 1 (data) report for Review 2: source/split tables, class distributions,
imbalance ratios, teacher agreement (Cohen's kappa) and charts.

Read-only over existing manifests and labels; writes output/review2/stage1/.
Usage: python scripts/stage1_report.py
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from sklearn.metrics import cohen_kappa_score  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
T = ROOT / "output/scorer_v3/teacher_labels"
OUT = ROOT / "output/review2/stage1"
SPLITS = ["train", "validation", "test"]
DEGREES = ["none", "high_school", "associate", "bachelor", "master", "doctorate"]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def cv_domains() -> dict[str, str]:
    gold = {c["cv_id"]: c["domain"] for c in load(ROOT / "data/processed/structured_cvs/all_cvs.json")}
    pool = {d["id"]: d["domain"] for d in load(T / "manifest.json")["documents"]}
    ext = {d["id"]: d["domain"] for d in load(T / "manifest_external.json")["documents"]}
    return {**gold, **pool, **ext}


def highest_degree(facts: dict) -> str:
    got = [d for d in facts.get("completed_degrees") or [] if d in DEGREES]
    return max(got, key=DEGREES.index) if got else "none"


def skill_names(doc: dict) -> set[str]:
    return {k.strip().lower() for s in doc.get("skills") or [] for k in s.get("keywords") or []}


def jaccard(a: set, b: set) -> float:
    return len(a & b) / len(a | b) if a | b else 1.0


def table(rows: list[list], head: list[str]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def crosstab(items: list[tuple[str, str]], cols: list[str]) -> tuple[list[list], list[str]]:
    c = Counter(items)
    keys = sorted({k for k, _ in items})
    rows = [[k, *(c[(k, s)] for s in cols), sum(c[(k, s)] for s in cols)] for k in keys]
    rows.append(["**Total**", *(sum(c[(k, s)] for k in keys) for s in cols), len(items)])
    return rows, cols


def imbalance(counts: Counter) -> str:
    hi, lo = max(counts.values()), min(counts.values())
    return f"{hi}/{lo} = {hi / lo:.2f}"


def bar(counts_by_split: dict[str, Counter], order: list[str], title: str, name: str) -> None:
    fig, ax = plt.subplots(figsize=(9, 4.5))
    width = 0.8 / len(counts_by_split)
    for i, (split, c) in enumerate(counts_by_split.items()):
        total = sum(c.values()) or 1
        xs = [x + i * width for x in range(len(order))]
        ax.bar(xs, [100 * c[k] / total for k in order], width, label=f"{split} (n={total})")
    ax.set_xticks([x + width * (len(counts_by_split) - 1) / 2 for x in range(len(order))])
    ax.set_xticklabels([k.replace("_", "\n") for k in order], fontsize=8)
    ax.set_ylabel("% of split")
    ax.set_title(title)
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT / f"{name}.png", dpi=160)
    plt.close(fig)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    tasks = load(ROOT / "data/datasets/qwen_training/manifest.json")["tasks"]
    cv, jd = tasks["cv_extraction"], tasks["jd_extraction"]
    dom = cv_domains()
    md = ["# Stage 1 - Data report (generated by scripts/stage1_report.py)\n"]

    # 1. Sources and splits
    md.append("## 1. CV extraction dataset: source x split\n")
    md.append(table(crosstab([(r["source"], r["split"]) for r in cv], SPLITS)[0], ["Source", *SPLITS, "Total"]))
    md.append("\n## 2. JD extraction dataset: batch x split\n")
    md.append(table(crosstab([(r["source"], r["split"]) for r in jd], SPLITS)[0], ["Batch", *SPLITS, "Total"]))
    jd_meta = {d["id"]: d for d in load(T / "jd/manifest.json")["documents"]}
    md.append("\n### JD language x split\n")
    md.append(table(crosstab([(jd_meta[r["id"]]["language"], r["split"]) for r in jd], SPLITS)[0], ["Language", *SPLITS, "Total"]))

    # 2. Class distributions
    cv_dom = {s: Counter(dom[r["id"]] for r in cv if r["split"] == s) for s in SPLITS}
    jd_dom = {s: Counter(jd_meta[r["id"]]["domain"] for r in jd if r["split"] == s) for s in SPLITS}
    cv_order = sorted(set().union(*cv_dom.values()))
    jd_order = sorted(set().union(*jd_dom.values()))
    md.append("\n## 3. CV domain x split\n")
    md.append(table(crosstab([(dom[r["id"]], r["split"]) for r in cv], SPLITS)[0], ["Domain", *SPLITS, "Total"]))
    md.append("\n## 4. JD domain x split\n")
    md.append(table(crosstab([(jd_meta[r["id"]]["domain"], r["split"]) for r in jd], SPLITS)[0], ["Domain", *SPLITS, "Total"]))
    bar(cv_dom, cv_order, "CV extraction: domain share per split", "cv_domain_by_split")
    bar(jd_dom, jd_order, "JD extraction: domain share per split", "jd_domain_by_split")

    label = {r["id"]: load(ROOT / r["label"]) for r in cv}
    cv_deg = {s: Counter(highest_degree(label[r["id"]]["facts"]) for r in cv if r["split"] == s) for s in SPLITS}
    md.append("\n## 5. CV highest completed degree x split\n")
    md.append(table([[d, *(cv_deg[s][d] for s in SPLITS)] for d in DEGREES], ["Degree", *SPLITS]))
    bar(cv_deg, DEGREES, "CV extraction: highest completed degree per split", "cv_degree_by_split")

    md.append("\n## 6. Label status (pass = fully verified, partial = verified with flagged fields)\n")
    md.append(table([[t, *(Counter(r["status"] for r in rows)[k] for k in ("pass", "partial"))] for t, rows in (("CV", cv), ("JD", jd))], ["Task", "pass", "partial"]))

    pairs = load(ROOT / "data/datasets/matching_pairs/benchmark_matching_pairs.json")
    grades = Counter(p["grade"] for p in pairs)
    md.append("\n## 7. Silver matching pairs (retrieval/scorer benchmark)\n")
    md.append(table([[g, grades[g], f"{100 * grades[g] / len(pairs):.1f}%"] for g in sorted(grades)], ["Grade", "Pairs", "Share"]))
    md.append("\n" + table([[k, v] for k, v in Counter(p["pair_type"] for p in pairs).most_common()], ["Pair type", "Pairs"]))
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.bar([f"g{g}" for g in sorted(grades)], [grades[g] for g in sorted(grades)], color=["#9aa5b1", "#4c78a8", "#f58518"])
    ax.set_title(f"Silver pairs by relevance grade (n={len(pairs)})")
    fig.tight_layout()
    fig.savefig(OUT / "silver_grades.png", dpi=160)
    plt.close(fig)

    # 3. Imbalance ratios (max/min class count, train split)
    md.append("\n## 8. Imbalance ratio (largest / smallest class, train split)\n")
    md.append(table([
        ["CV domain", imbalance(cv_dom["train"])],
        ["JD domain", imbalance(jd_dom["train"])],
        ["CV degree (non-zero classes)", imbalance(+cv_deg["train"])],
        ["Silver grade (all pairs)", imbalance(grades)],
    ], ["Dimension", "Ratio"]))

    # 4. Teacher agreement on the local CV pool (two independent teachers, before arbitration)
    ids = sorted({p.stem for p in (T / "haiku_b").glob("*.json")} & {p.stem for p in (T / "gemini_b").glob("*.json")})
    a = {i: load(T / "haiku_b" / f"{i}.json") for i in ids}
    b = {i: load(T / "gemini_b" / f"{i}.json") for i in ids}
    deg_a = [highest_degree(a[i]["facts"]) for i in ids]
    deg_b = [highest_degree(b[i]["facts"]) for i in ids]
    all_dom = sorted({d for x in (a, b) for i in ids for d in x[i]["facts"].get("domains") or []})
    dom_k = {d: cohen_kappa_score([d in (a[i]["facts"].get("domains") or []) for i in ids],
                                  [d in (b[i]["facts"].get("domains") or []) for i in ids]) for d in all_dom}
    support = Counter(d for x in (a, b) for i in ids for d in x[i]["facts"].get("domains") or [])
    jac = sorted(jaccard(skill_names(a[i]["document"]), skill_names(b[i]["document"])) for i in ids)
    n_ext = sum(i.startswith("ex_") for i in ids)
    md.append(f"\n## 9. Inter-teacher agreement (Haiku vs Gemini, n={len(ids)} CVs: {len(ids) - n_ext} local pool + {n_ext} external, before arbitration)\n")
    md.append(table([
        ["Highest degree: Cohen's kappa", f"{cohen_kappa_score(deg_a, deg_b):.3f}"],
        ["Highest degree: quadratic-weighted kappa",
         f"{cohen_kappa_score([DEGREES.index(x) for x in deg_a], [DEGREES.index(x) for x in deg_b], weights='quadratic'):.3f}"],
        ["Highest degree: raw agreement", f"{sum(x == y for x, y in zip(deg_a, deg_b)) / len(ids):.3f}"],
        ["Domains: mean per-domain kappa (domains with >=20 mentions)",
         f"{sum(dom_k[d] for d in dom_k if support[d] >= 20) / sum(support[d] >= 20 for d in dom_k):.3f}"],
        ["Skills: mean Jaccard of skill names", f"{sum(jac) / len(jac):.3f} (median {jac[len(jac) // 2]:.3f})"],
    ], ["Measure", "Value"]))
    md.append("\nPer-domain kappa:\n")
    md.append(table([[d, support[d], f"{dom_k[d]:.3f}"] for d in sorted(dom_k, key=lambda d: -support[d])], ["Domain", "Mentions (both teachers)", "Kappa"]))

    pool_split = Counter(d["split"] for d in load(T / "manifest.json")["documents"])
    drop = load(T / "manifest_external.json")["dropped"]
    md.append(f"""
## 10. Cleaning and labelling flow

```mermaid
flowchart TD
  A[Local CV PDFs: 601 files, 6 domains] --> B[Exact-hash dedup: 577 distinct]
  B --> G[Gold set: 88 human-checked CVs, 86 converted to v3]
  B --> P[Teacher pool: {sum(pool_split.values())} CVs<br/>train {pool_split['train']} / reserved val {pool_split['validation']} + test {pool_split['test']} / pilot {pool_split['pilot']}]
  E[External: Saba06 2,484 rows + med2425 638 unique CVs] --> F[Drop other domains {drop['other_domain']}, local copies {drop['local_copy']},<br/>scorer-test CVs {drop['scorer_test']}, external copies {drop['external_copy']}]
  F --> X[External train pool: {sum(1 for r in cv if r['source'].startswith('external'))} CVs]
  P --> T2[Two teachers: Haiku + Gemini, independent]
  X --> T2
  T2 --> R[Blinded arbiter on disagreements + rule sweeps]
  R --> V[Machine validation: schema, exact-quote evidence, dates]
  G --> V
  V --> S[CV SFT set: {len(cv)} rows = train {sum(r['split'] == 'train' for r in cv)} / val 12 gold / test 12 gold]
  J[CareerViet JDs: {len(jd)} - EN/mixed {sum(jd_meta[r['id']]['language'] != 'vi' for r in jd)}, VI {sum(jd_meta[r['id']]['language'] == 'vi' for r in jd)}] --> JT[Gemini teacher + Codex judge + sweeps]
  JT --> JV[Machine validation] --> JS[JD SFT set: train {sum(r['split'] == 'train' for r in jd)} / val 54 / test 54]
```
""")

    (OUT / "stage1_report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
