"""Side-by-side test scores (with 95% CIs) for every Qwen model, plus the training/validation loss curves.

Usage: python -m scripts.qwen_compare
Reads output/review2/qwen/*.scores.json and */log_history.json; writes model_comparison.md and loss_curves.png there.
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from scripts.qwen_eval import DATA, parse, skills

QWEN = Path(__file__).resolve().parent.parent / "output/review2/qwen"
MODELS = (("raw Qwen", "base_rp_test"), ("V2", "v2_rp_test"), ("V3a", "v3_rp_test"), ("V3b", "v3b_rp_test"), ("V4", "v4_rp_test"),
          ("V4 + repair/retry", "v4_final_test"))
LOGS = (("V2", "log_history.json"), ("V3a", "v3a/log_history.json"), ("V3b", "v3b/log_history.json"), ("V4", "v4/log_history.json"))


def density(stem: str, task: str) -> float:
    """Mean skills per parsed document: shows whether a model copies the dense teacher style or the sparser gold style."""
    preds = [parse(r["prediction"]) for line in (QWEN / f"{stem}.jsonl").read_text(encoding="utf-8").splitlines()
             if (r := json.loads(line))["task"] == task]
    parsed = [p for p in preds if p]
    return sum(len(skills(p, task)) for p in parsed) / len(parsed)


def main() -> None:
    scores = {name: json.loads((QWEN / f"{stem}.scores.json").read_text()) for name, stem in MODELS}
    md = ["# Qwen extraction: model comparison on the test split (generated by scripts/qwen_compare.py)\n",
          "All generations greedy with repetition penalty 1.05. Value [95% bootstrap CI over documents]. Single seed.\n"]
    for task in ("cv_extraction", "jd_extraction"):
        ns = {s[task]["n"] for s in scores.values()}
        assert len(ns) == 1, f"{task}: models scored on different test sets {ns}"
        md += [f"## {task} (n={ns.pop()})\n", "| Metric | " + " | ".join(scores) + " |", "|---" * (len(scores) + 1) + "|",
               "| truncated (loops) | " + " | ".join(str(s[task]["truncated"]) for s in scores.values()) + " |"]
        for key, m in scores["V3b"][task].items():
            if isinstance(m, dict):
                md.append(f"| {key} | " + " | ".join(f"{s[task][key]['value']:.2f} [{s[task][key]['ci95'][0]:.2f}, "
                                                    f"{s[task][key]['ci95'][1]:.2f}]" for s in scores.values()) + " |")
        gold = [skills(json.loads(json.loads(line)["messages"][2]["content"]), task)
                for line in (DATA / task / "test.jsonl").read_text(encoding="utf-8").splitlines()]
        md.append("| skills per parsed doc | " + " | ".join(f"{density(stem, task):.1f}" for _, stem in MODELS) +
                  f" |\n\nGold: {sum(map(len, gold)) / len(gold):.1f} skills per document.\n")

    fig, (ax_t, ax_v) = plt.subplots(1, 2, figsize=(11, 4))
    for name, rel in LOGS:
        log = json.loads((QWEN / rel).read_text())
        ax_t.plot(*zip(*[(r["step"], r["loss"]) for r in log if "loss" in r]), label=name, lw=1)
        ax_v.plot(*zip(*[(r["step"], r["eval_loss"]) for r in log if "eval_loss" in r]), label=name, marker="o")
    for ax, title in ((ax_t, "Training loss"), (ax_v, "Validation loss")):
        ax.set(title=title, xlabel="optimizer step", ylabel="loss")
        ax.legend()
    fig.tight_layout()
    fig.savefig(QWEN / "loss_curves.png", dpi=150)
    md.append("![loss curves](loss_curves.png)\n")
    (QWEN / "model_comparison.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
