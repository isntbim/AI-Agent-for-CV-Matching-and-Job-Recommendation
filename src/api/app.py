@asynccontextmanager
async def lifespan(app: FastAPI):
    STATE["ranker"] = svc.corpus_ranker()  # bge-m3 + TF-IDF over the corpus, loaded once (~20 s on CPU)
    STATE["paths"] = svc._jd_paths()
    svc._retrieval_index(), svc._llm()  # bge-m3 index and extractor tokenizer: load now, not on the first request
    yield


app = FastAPI(title="CV Matching AI Agent", lifespan=lifespan)

# --- monitoring: Prometheus scrapes /metrics (docker/monitoring/ has the Prometheus + Grafana setup)
RESPONSE = Histogram("api_response_seconds", "API response time (to the first byte for streams)", ["route", "status"],
                     buckets=(.01, .05, .1, .25, .5, 1, 2.5, 5, 10, 30, 60, 120))
MATCH_SECONDS = Histogram("match_seconds", "Whole match time, extraction to ranking", buckets=(1, 2, 5, 10, 20, 30, 45, 60, 90, 120, 300))
