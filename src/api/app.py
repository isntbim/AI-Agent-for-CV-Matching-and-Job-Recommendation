class ResourceCollector:
    """Read at each scrape: CPU and RAM of this host and process, VRAM held by each model in Ollama, and GPU use
    where nvidia-smi exists (the host, not the API container; there the Ollama VRAM figure still works)."""

    def collect(self):
        import shutil
        import subprocess

        import httpx
        import psutil
        g = GaugeMetricFamily("host_cpu_percent", "Host CPU use")
        g.add_metric([], psutil.cpu_percent(None))
        yield g
        g = GaugeMetricFamily("host_memory_used_bytes", "Host RAM in use")
        g.add_metric([], psutil.virtual_memory().used)
        yield g
        g = GaugeMetricFamily("api_process_memory_bytes", "Resident memory of the API process")
        g.add_metric([], psutil.Process().memory_info().rss)
        yield g
        g = GaugeMetricFamily("ollama_model_vram_bytes", "VRAM held by each model loaded in Ollama", labels=["model"])
        try:
            for m in httpx.get(os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434") + "/api/ps", timeout=1).json()["models"]:
                g.add_metric([m["name"]], m.get("size_vram", 0))
        except (httpx.HTTPError, ValueError, KeyError):
            pass
        yield g
        if shutil.which("nvidia-smi"):
            try:
                util, used = subprocess.run(["nvidia-smi", "--query-gpu=utilization.gpu,memory.used", "--format=csv,noheader,nounits"],
                                            capture_output=True, text=True, timeout=3).stdout.splitlines()[0].split(",")
                for name, help_, value in (("gpu_utilization_percent", "GPU use", float(util)),
                                           ("gpu_memory_used_bytes", "GPU memory in use", float(used) * 2**20)):
                    g = GaugeMetricFamily(name, help_)
                    g.add_metric([], value)
                    yield g
            except (OSError, ValueError, IndexError, subprocess.SubprocessError):
                pass


REGISTRY.register(ResourceCollector())
app.mount("/metrics", make_asgi_app())


@app.middleware("http")
async def timing(request: Request, call_next):
    start = time.perf_counter()
    response = await call_next(request)
    route = getattr(request.scope.get("route"), "path", None)  # the route template, so /api/history/{run_id} is one series
    if route and route != "/metrics":
        RESPONSE.labels(route, str(response.status_code)).observe(time.perf_counter() - start)
    return response
